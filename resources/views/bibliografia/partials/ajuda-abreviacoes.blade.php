      <div class="modal-body bg-light text-dark">
        <p>As referências bibliográficas utilizam abreviações para indicar diferentes elementos da publicação. As mais comuns são:</p>

        <!-- Lista simples -->
        <ul class="mb-3">
          <li><strong class="text-info">ed.</strong> — edição. Ex.: 2. ed.</li>
          <li><strong class="text-info">org.</strong> — organizador(es).</li>
          <li><strong class="text-info">coord.</strong> — coordenador(es).</li>
          <li><strong class="text-info">trad.</strong> — tradutor(es).</li>
          <li><strong class="text-info">rev.</strong> — revisor(es).</li>
          <li><strong class="text-info">v.</strong> — volume. Ex.: v. 2.</li>
          <li><strong class="text-info">n.</strong> — número da publicação ou fascículo. Ex.: n. 3.</li>
          <li><strong class="text-info">p.</strong> — página(s). Ex.: p. 25-40.</li>
          <li><strong class="text-info">et al.</strong> — expressão latina que significa “e outros”, utilizada para indicar autores adicionais.</li>
          <li><strong class="text-info">In:</strong> — indica que o trabalho citado faz parte de uma obra maior, como um capítulo de livro ou trabalho publicado em anais.</li>
          <li><strong class="text-info">s.d.</strong> — sem data. Utilizada quando não é possível identificar o ano de publicação.</li>
          <li><strong class="text-info">s.l.</strong> — sem local. Utilizada quando o local de publicação não é identificado.</li>
          <li><strong class="text-info">s.n.</strong> — sem nome de editor ou editora. Utilizada quando o responsável pela publicação não é identificado.</li>
          <li><strong class="text-info">[s.d.], [s.l.], [s.n.]</strong> — indicações entre colchetes utilizadas para sinalizar que a informação não está disponível ou não pôde ser identificada.</li>
        </ul>

        <!-- Observação -->
        <div class="alert alert-info border-info mb-0 small" role="alert">
          <strong>Observação:</strong> As abreviações podem variar conforme o tipo de documento e a norma bibliográfica adotada. O Assistente Bibliográfico procura aplicar a forma adequada ao contexto da referência e da norma selecionada.
